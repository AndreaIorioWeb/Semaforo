    const $ = ctx.$;
    const missing: string[] = [];
    if (!$("title").first().text().trim()) missing.push("titolo della pagina (title)");
    if (!$('meta[name="description" i]').attr("content")?.trim()) missing.push("descrizione (meta description)");
