/** Regole di robots.txt per un user agent (parser minimale, sufficiente per Disallow / e Sitemap). */
export function robotsGroups(robots: string): Array<{ agents: string[]; disallow: string[]; allow: string[] }> {
  const groups: Array<{ agents: string[]; disallow: string[]; allow: string[] }> = [];
  let current: { agents: string[]; disallow: string[]; allow: string[] } | undefined;
  let lastWasAgent = false;
  for (const rawLine of robots.split(/\r?\n/)) {
    const line = rawLine.replace(/#.*$/, "").trim();
    const m = /^([A-Za-z-]+)\s*:\s*(.*)$/.exec(line);
    if (!m) continue;
    const key = (m[1] ?? "").toLowerCase();
    const value = (m[2] ?? "").trim();
    if (key === "user-agent") {
      if (!current || !lastWasAgent) {
        current = { agents: [], disallow: [], allow: [] };
        groups.push(current);
      }
      current.agents.push(value.toLowerCase());
      lastWasAgent = true;
      continue;
    }
    lastWasAgent = false;
    if (!current) continue;
    if (key === "disallow" && value !== "") current.disallow.push(value);
    if (key === "allow" && value !== "") current.allow.push(value);
  }
  return groups;
}

export function robotsBlocksAll(robots: string, agent = "*"): boolean {
  const groups = robotsGroups(robots);
  const group = groups.find((g) => g.agents.includes(agent.toLowerCase())) ?? groups.find((g) => g.agents.includes("*"));
  if (!group) return false;
  return group.disallow.includes("/") && !group.allow.some((a) => a === "/" || a === "/$");
}

export function robotsSitemaps(robots: string): string[] {
  return [...robots.matchAll(/^\s*sitemap\s*:\s*(\S+)/gim)].map((m) => m[1] ?? "").filter(Boolean);
}

export const pub001: Check = {
  id: "PUB-001",
  run(ctx) {
    const evidence: string[] = [];
    const metaRobots = ctx.$('meta[name="robots" i], meta[name="googlebot" i]')
      .map((_, el) => ctx.$(el).attr("content") ?? "")
      .get()
      .join(", ");
    if (/noindex/i.test(metaRobots)) evidence.push(`meta robots: "${metaRobots}"`);
    const xRobots = headerValue(ctx.headers, "x-robots-tag");
    if (xRobots && /noindex/i.test(xRobots)) evidence.push(`header X-Robots-Tag: "${xRobots}"`);
    if (ctx.robotsTxt && (robotsBlocksAll(ctx.robotsTxt, "*") || robotsBlocksAll(ctx.robotsTxt, "googlebot"))) {
      evidence.push("robots.txt contiene \"Disallow: /\" per tutti i motori");
    }
    if (evidence.length > 0) {
      return [
        finding("PUB-001", {
          status: "ko",
          severity: "high",
          explanation:
            "Il sito chiede ai motori di ricerca di non comparire nei risultati. Succede spesso quando si dimentica attiva l'opzione usata durante lo sviluppo.",
          evidence,
          howToFix:
            "Togli il noindex (in WordPress: Impostazioni > Lettura, togli la spunta a \"Scoraggia i motori di ricerca\") e rimuovi \"Disallow: /\" da robots.txt.",
        }),
      ];
    }
    return [
      finding("PUB-001", {
        status: "ok",
        severity: "info",
        explanation: "Il sito non blocca i motori di ricerca.",
        howToFix: "Nessuna azione necessaria.",
      }),
    ];
  },
};

