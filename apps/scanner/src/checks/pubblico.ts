export const pub006: Check = {
  id: "PUB-006",
  run(ctx) {
    if (ctx.robotsTxt === undefined && ctx.sitemapFound === undefined) return [];
    const issues: string[] = [];
    if (ctx.robotsTxt === null) issues.push("robots.txt non presente");
    if (ctx.sitemapFound === false) issues.push("sitemap non trovata");
    if (typeof ctx.robotsTxt === "string" && ctx.sitemapFound && robotsSitemaps(ctx.robotsTxt).length === 0) {
      issues.push("robots.txt non indica la sitemap");
    }
    if (issues.length === 0) {
      return [
        finding("PUB-006", {
          status: "ok",
          severity: "info",
          explanation: "robots.txt e sitemap sono presenti e collegati.",
          howToFix: "Nessuna azione necessaria.",
        }),
      ];
    }
    return [
      finding("PUB-006", {
        status: "warn",
        severity: "low",
        explanation: "robots.txt e sitemap aiutano i motori di ricerca a trovare tutte le pagine del sito.",
        evidence: issues,
        howToFix: "Pubblica /sitemap.xml e aggiungi in robots.txt la riga \"Sitemap: https://tuosito/sitemap.xml\".",
      }),
    ];
  },
};

